"""Writes lib/src/hint_cases.nr: UseHint test cases for gamma2 = (q - 1) / 32 with expected values from a direct
transcription of FIPS 204 Algorithms 36 (Decompose) and 40 (UseHint), independent of the circuit's method.

Cases: every decomposition boundary (0, 1, gamma2 +- 1, each multiple of 2 * gamma2 +- 1, each multiple plus
gamma2 +- 1, q - gamma2 +- 1, q - 2, q - 1) and a seeded random sample, each for h = 0 and h = 1.
"""
import os
import random

Q = 8380417

GAMMA2 = (Q - 1) // 32

ALPHA = 2 * GAMMA2

SAMPLES = 500

SEED = 204


def decompose(r):
    rp = r % Q

    r0 = rp % ALPHA

    if r0 > ALPHA // 2:
        r0 -= ALPHA

    if rp - r0 == Q - 1:
        return 0, r0 - 1

    return (rp - r0) // ALPHA, r0


def use_hint(h, r):
    r1, r0 = decompose(r)

    if h == 1 and r0 > 0:
        return (r1 + 1) % 16

    if h == 1 and r0 <= 0:
        return (r1 - 1) % 16

    return r1


def boundaries():
    values = {0, 1, GAMMA2 - 1, GAMMA2, GAMMA2 + 1, Q - GAMMA2 - 1, Q - GAMMA2, Q - GAMMA2 + 1, Q - 2, Q - 1}

    for k in range(17):
        for d in (-1, 0, 1):
            values.add(k * ALPHA + d)

            values.add(k * ALPHA + GAMMA2 + d)

    return sorted(v for v in values if 0 <= v < Q)


def main():
    rng = random.Random(SEED)

    edge = boundaries()

    sample = sorted(rng.randrange(Q) for _ in range(SAMPLES))

    cases = [(r, h, use_hint(h, r)) for r in edge + sample for h in (0, 1)]

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    body = ",\n".join(f"    ({r}, {h}, {e})" for r, h, e in cases)

    text = f"// Generated by scripts/gen_use_hint_cases.py: {len(edge)} boundary values and {SAMPLES} random values (seed {SEED}),\n// each for h = 0 and h = 1, with expected outputs from FIPS 204 Algorithms 36 and 40.\npub(crate) global USE_HINT_CASES: [(Field, Field, Field); {len(cases)}] = [\n{body},\n];\n"

    open(os.path.join(root, "lib", "src", "hint_cases.nr"), "w").write(text)

    print(f"wrote {len(cases)} UseHint cases ({len(edge)} boundary values, {SAMPLES} random values)")


if __name__ == "__main__":
    main()
